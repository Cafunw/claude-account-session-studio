let current: Lang = typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("tr") ? "tr" : "en";

export const setLang = (l: Lang) => {
  current = l;
};
export const getLang = () => current;
/** BCP 47 locale for `Intl` and `toLocale*` calls. */
export const locale = () => (current === "tr" ? "tr-TR" : "en-US");

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  let s: string | Plural = (current === "tr" ? tr : en)[key];
  if (typeof s !== "string") s = s[new Intl.PluralRules(locale()).select(Number(vars.n)) === "one" ? "one" : "other"];
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

/** "%34" in Turkish, "34%" in English. */
export const pct = (n: number) => t("fmt.pct", { n: Math.round(n) });

